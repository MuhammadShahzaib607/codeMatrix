const block = (vars) => `:root {\n${Object.entries(vars).map(([key, value]) => `  --${key}: ${value};`).join('\n')}\n}\n`

const fontsHref = (fonts) => {
  const families = fonts.map((font) => `family=${font.family.replace(/ /g, '+')}:wght@${font.weights}`)
  return `https://fonts.googleapis.com/css2?${families.join('&')}&display=swap`
}

