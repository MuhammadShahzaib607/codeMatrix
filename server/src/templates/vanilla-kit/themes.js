export const DEFAULT_THEME_ID = 'indigo-modern'

export function getThemePreset(id) {
  const wanted = String(id ?? '').trim().toLowerCase()
  return THEME_PRESETS.find((preset) => preset.id === wanted) ?? THEME_PRESETS[0]
}

export function themePresetIds() {
  return THEME_PRESETS.map((preset) => preset.id)
}

